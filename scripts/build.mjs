import { cp, mkdir, rm, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { prepareAssets } from './prepare-assets.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
for (const file of await readdir(resolve(root, 'src'))) if (file.endsWith('.js')) execFileSync(process.execPath, ['--check', resolve(root, 'src', file)], { stdio: 'inherit' });
await prepareAssets();
await rm(resolve(root, 'dist'), { recursive: true, force: true });
await mkdir(resolve(root, 'dist'), { recursive: true });
for (const item of ['index.html', 'src', 'assets']) await cp(resolve(root, item), resolve(root, 'dist', item), { recursive: true });
console.log('Built dist/ with local PDF parsing, math fonts and sample material.');
